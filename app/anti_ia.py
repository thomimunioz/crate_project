"""Detecta canales de musica generada con IA, para no volver a colarlos.

El caso (27-oct): el canal "Winta Groove" tiene 683 temas de solo 11 "artistas"
— Winta (272), Liora Twani (200), Winta & Liora Twani (201). Thomas lo cazo de
oido: "esto es GRAVISIMO: ES MUSICA HECHA CON IA". Para entonces yo ya le habia
mandado uno y el le habia puesto 5 estrellas.

La señal es inequivoca y barata: un canal de digging real sube artistas
DISTINTOS. Winta Groove tiene ratio temas/artistas de 62; el resto del pool, de
1.0 a 6.5. Sin solapamiento.

Uso:
    from anti_ia import sospechoso, RATIO_MAX, CONCENTRACION_MAX
    sospechoso(lista_de_titulos) -> (bool, motivo)
"""
import re
from collections import Counter

RATIO_MAX = 8.0          # temas por artista distinto
CONCENTRACION_MAX = 25   # % del catalogo que puede tener UN solo artista
MINIMO = 40              # debajo de esto no hay muestra para juzgar

# canales ya verificados a mano
VETADOS = {"Winta Groove"}

# marcas tipicas de las plataformas de generacion
MARCAS_IA = re.compile(
    r"\b(suno|udio|boomy|soundraw|aiva|mubert|riffusion|stable ?audio|"
    r"ai ?generated|generated by ai|made with ai|ai ?music|neural ?music)\b", re.I)


def artista_de(titulo):
    t = re.sub(r"^\s*\[[^\]]*\]\s*", "", titulo or "")
    return re.split(r"\s+[-–—]\s+|\s*:\s+|\s*♪", t, 1)[0].strip().lower()[:28]


def sospechoso(titulos, canal=None):
    """Devuelve (es_sospechoso, motivo) para el catalogo de un canal."""
    if canal and canal in VETADOS:
        return True, "canal vetado a mano"
    if any(MARCAS_IA.search(t or "") for t in titulos):
        return True, "el titulo nombra una plataforma de generacion"
    if len(titulos) < MINIMO:
        return False, ""
    arts = [artista_de(t) for t in titulos]
    distintos = len(set(arts))
    ratio = len(titulos) / max(1, distintos)
    if ratio >= RATIO_MAX:
        return True, "%d temas de solo %d artistas (ratio %.0f)" % (
            len(titulos), distintos, ratio)
    top, n = Counter(arts).most_common(1)[0]
    conc = 100.0 * n / len(titulos)
    if conc >= CONCENTRACION_MAX:
        return True, "un solo artista ('%s') es el %.0f%% del canal" % (top[:24], conc)
    return False, ""


if __name__ == "__main__":
    import json, os, sys
    from collections import defaultdict
    HERE = os.path.dirname(os.path.abspath(__file__))
    por = defaultdict(list)
    for f in ("demo_cavado.json", "vetas_pool.json", "fsr_nuevo.json",
              "ws_pool.json", "latam_pool.json"):
        p = os.path.join(HERE, f)
        if os.path.exists(p):
            for v in json.load(open(p, encoding="utf-8")).values():
                por[v.get("uploader") or "?"].append(v.get("title") or "")
    malos = []
    for u, ts in sorted(por.items(), key=lambda kv: -len(kv[1])):
        mal, por_que = sospechoso(ts, u)
        if mal:
            malos.append((u, len(ts), por_que))
    print("canales analizados: %d" % len(por))
    if malos:
        print("SOSPECHOSOS:")
        for u, n, m in malos:
            print("   %-28s %5d temas  -> %s" % (u[:28], n, m))
    else:
        print("ninguno sospechoso")
